use crate::{display::Screen, lvgl_sys};
use lvgl_sys::*;

// --- CONSTANTS ---
const EVT_DRAW_PART_BEGIN: lv_event_code_t = lv_event_code_t_LV_EVENT_DRAW_PART_BEGIN;
const EVT_ALL: lv_event_code_t = lv_event_code_t_LV_EVENT_ALL;

#[unsafe(link_section = ".data")]
static VANE_DIR: [&core::ffi::CStr; 5] = [c"N", c"E", c"S", c"W", c""];

// Dimensions for 800x480 screen
const METER_CENTER_X: f32 = 400.0;
const METER_CENTER_Y: f32 = 240.0;
const METER_RADIUS: f32 = 133.0; // Slightly reduced so arrow stays inside and placed over the ticks

/*******************************************************************************************
 *  STATICS STORAGE FOR LVGL OBJECTS
 ******************************************************************************************/
static mut METER_PTR: *mut lv_obj_t = core::ptr::null_mut();

pub struct WeatherVanePage {
    arrow_image: *mut lv_obj_t,
}

impl WeatherVanePage {
    pub fn new(screen: Screen) -> Self {
        unsafe {
            // --- Get pointer to the screen ---
            let screen_ptr = screen.as_ptr();

            // --- Style the Screen ---
            lv_obj_set_style_bg_color(screen_ptr, color_from_rgb(53, 56, 57), 0);
            lv_obj_set_style_bg_opa(screen_ptr, 255, 0);

            // --- Create Meter ---
            let meter = lv_meter_create(screen_ptr);
            METER_PTR = meter; // Store globally for callback
            lv_obj_set_size(meter, 320, 320);
            let meter_pos_x = (METER_CENTER_X - 160.0) as i16;
            let meter_pos_y = (METER_CENTER_Y - 160.0) as i16;
            lv_obj_set_pos(meter, meter_pos_x, meter_pos_y);
            //lv_obj_align(meter, LV_ALIGN_CENTER as u8, 0, 0);

            // --- Add a scale for the 360 degrees of a weather vane ---
            let scale = lv_meter_add_scale(meter);
            // 360 span makes a full circle.
            // 270 rotation offsets the start point so 0 is at 12 o'clock.
            lv_meter_set_scale_range(meter, scale, 0, 360, 360, 270);

            // ticks: 17 (0 to 16)
            // tick width: 2, tick length: 10, tick_color: a light grey
            lv_meter_set_scale_ticks(meter, scale, 17, 2, 10, color_from_rgb(150, 150, 150));

            // major_tick_every: 4 (16 / 4 = 4, so majorticks at 0, 90, 180, 270)
            // tick_width: 4, tick_length: 20, tick_color: blue, label_gap: 15
            let tick_color = color_from_rgb(0, 0, 255);
            lv_meter_set_scale_major_ticks(meter, scale, 4, 4, 20, tick_color, 15);

            // Had to use image instead of GPS symbol for label because you can't angle a label
            // which I needed to do otherwise GPS symbol would look wierd on meter at different degrees.
            // Create the arrow image
            init_arrow_descriptor();
            let arrow_image = lv_img_create(screen_ptr);
            lv_img_set_src(arrow_image, &raw const ARROW_IMG_DSC as *const _);
            lv_img_set_pivot(arrow_image, 12, 12);

            lv_obj_add_event_cb(meter, Some(meter_event_cb), EVT_ALL, core::ptr::null_mut());

            Self { arrow_image }
        }
    }

    pub fn update_gps_symbol_pos(&mut self, bearing: f32) {
        let angle_rad = (bearing - 90.0) * (core::f32::consts::PI / 180.0);

        // Calculate position
        let x = METER_CENTER_X + (METER_RADIUS * libm::cosf(angle_rad));
        let y = METER_CENTER_Y + (METER_RADIUS * libm::sinf(angle_rad));

        unsafe {
            // 1. Move the image (centered on the coordinate)
            // 12 is half of your 24px image width/height
            lv_obj_set_pos(self.arrow_image, (x - 12.0) as i16, (y - 12.0) as i16);

            // Add 90 degrees to correct for the West-pointing source image
            // We use % 3600 to keep it within the 0-3600 range (0.1 deg units)
            let corrected_angle = ((bearing * 10.0) as i32 + 900) % 3600;

            lv_img_set_angle(self.arrow_image, corrected_angle as i16);
        }
    }
}

// C-style callback
#[esp_hal::ram]
unsafe extern "C" fn meter_event_cb(e: *mut lv_event_t) {
    unsafe {
        let code = lv_event_get_code(e);
        if code == EVT_DRAW_PART_BEGIN {
            let dsc = &mut *(lv_event_get_param(e) as *mut lv_obj_draw_part_dsc_t);

            // Ensure text is not null (only major ticks have text)
            if dsc.part == LV_PART_TICKS && !dsc.text.is_null() {
                // Map the numerical value to our Compass Strings
                let label = match dsc.value {
                    0 | 360 => VANE_DIR[0], // N
                    90 => VANE_DIR[1],      // E
                    180 => VANE_DIR[2],     // S
                    270 => VANE_DIR[3],     // W
                    _ => c"",               // Hide other numbers
                };

                // Use are text: N, E, S, W instead of numbers 360, 90, 180, 270
                dsc.text = label.as_ptr() as *mut core::ffi::c_char;
            }
        }
    }
}

/*******************************************************************************************
 *  LVGL Helpers
 ******************************************************************************************/
#[inline(always)]
const fn color_from_rgb(r: u8, g: u8, b: u8) -> lv_color_t {
    // Scale 8-bit colors down to 5-6-5 bit depths
    // Red:   8 bits -> 5 bits (r >> 3)
    // Green: 8 bits -> 6 bits (g >> 2)
    // Blue:  8 bits -> 5 bits (b >> 3)
    let r5 = (r >> 3) as u16;
    let g6 = (g >> 2) as u16;
    let b5 = (b >> 3) as u16;

    // Manually pack the RGB565 bits:
    // Red   is bits 11-15
    // Green is bits 5-10
    // Blue  is bits 0-4
    let full = (r5 << 11) | (g6 << 5) | b5;

    lv_color_t { full }
}

